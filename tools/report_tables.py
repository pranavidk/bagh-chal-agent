"""Build the report's appendix tables from the committed experiment CSVs.

    python tools/report_tables.py      # writes docs/report/tables_appendix.md

Reads results/e1_raw.csv and results/e2_raw.csv only; never re-runs experiments.
Tables only, no interpretation (PRD §6.1: Claude Code drafts tables from results).
"""
from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean, median

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
OUT = ROOT / "docs" / "report" / "tables_appendix.md"


def read(name):
    with open(RESULTS / name, newline="") as f:
        return list(csv.DictReader(f))


def e1_per_position(rows, depth):
    by_key = {(r["position_id"], r["algorithm"]): r for r in rows if int(r["depth"]) == depth}
    ids = sorted({pid for pid, _ in by_key}, key=lambda p: (p[0] != "P", p))
    lines = [
        f"### Table A{1 if depth == 4 else 2}. E1 per position, depth {depth}",
        "",
        "| Position | Phase | To move | Minimax nodes | Alpha-beta nodes | AB / MM | Root score | Minimax move | Alpha-beta move |",
        "|---|---|---|---:|---:|---:|---:|---|---|",
    ]
    for pid in ids:
        mm, ab = by_key[(pid, "minimax")], by_key[(pid, "alphabeta")]
        ratio = int(ab["nodes"]) / int(mm["nodes"])
        lines.append(f"| {pid} | {mm['phase']} | {mm['to_move']} | {int(mm['nodes']):,} | "
                     f"{int(ab['nodes']):,} | {ratio:.1%} | {float(mm['score']):g} | "
                     f"{mm['move']} | {ab['move']} |")
    return lines


def e1_agreement(rows):
    pairs = defaultdict(dict)
    for r in rows:
        pairs[(r["position_id"], int(r["depth"]))][r["algorithm"]] = r
    lines = [
        "### Table A3. E1 root agreement between minimax and alpha-beta",
        "",
        "| Depth | Pairs | Same score | Same move | Different move, same score |",
        "|---:|---:|---:|---:|---:|",
    ]
    for depth in sorted({d for _, d in pairs}):
        group = [v for (_, d), v in pairs.items() if d == depth]
        same_score = sum(float(g["minimax"]["score"]) == float(g["alphabeta"]["score"]) for g in group)
        same_move = sum(g["minimax"]["move"] == g["alphabeta"]["move"] for g in group)
        lines.append(f"| {depth} | {len(group)} | {same_score} | {same_move} | {len(group) - same_move} |")
    return lines


def e2_outcomes(rows):
    lines = [
        "### Table A4. E2 outcomes by how the game ended",
        "",
        "| Designed eval plays | Tigers won | of which by 5 captures | Goats won | Draw (repetition) | "
        "Draw (move cap) | Mean plies | Median plies | Mean goats captured |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for side in ("TIGER", "GOAT"):
        games = [r for r in rows if r["designed_side"] == side]
        winners = Counter(r["winner"] for r in games)
        capped = sum(r["capped"] == "True" for r in games)
        draws = winners.get("DRAW", 0)
        plies = [int(r["plies"]) for r in games]
        by_capture = sum(r["winner"] == "TIGER" and int(r["goats_captured"]) >= 5 for r in games)
        lines.append(f"| {side.title()} | {winners.get('TIGER', 0)} | {by_capture} | {winners.get('GOAT', 0)} | "
                     f"{draws - capped} | {capped} | {mean(plies):.1f} | {median(plies):g} | "
                     f"{mean(int(r['goats_captured']) for r in games):.2f} |")
    lines += [
        "",
        "Goat wins are always traps (R8.2). A tiger win not by 5 captures would be R8.3 (goat has no move).",
        "",
        "### Table A5. E2 goats captured per game",
        "",
        "| Designed eval plays | 0 | 1 | 2 | 3 | 4 | 5 |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for side in ("TIGER", "GOAT"):
        counts = Counter(int(r["goats_captured"]) for r in rows if r["designed_side"] == side)
        lines.append(f"| {side.title()} | " + " | ".join(str(counts.get(k, 0)) for k in range(6)) + " |")
    return lines


def main() -> None:
    e1, e2 = read("e1_raw.csv"), read("e2_raw.csv")
    parts = [
        "# Appendix tables",
        "",
        "Generated by `python tools/report_tables.py` from `results/e1_raw.csv` and "
        "`results/e2_raw.csv`. Tables only; interpretation is written by the team.",
        "",
        *e1_per_position(e1, 4), "",
        *e1_per_position(e1, 3), "",
        *e1_agreement(e1), "",
        *e2_outcomes(e2), "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
